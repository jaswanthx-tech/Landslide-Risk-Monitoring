"""
SQLAlchemy ORM Models for NER Landslide Sentinel
Defines entities for risk locations, active alerts, citizen incident reports,
and historical ground-truth landslide records.
"""

from datetime import datetime
from sqlalchemy import (
    Column,
    Integer,
    String,
    Float,
    Boolean,
    DateTime,
    Text
)
from app.database.database import Base


class RiskLocation(Base):
    """
    Monitoring zones and key transit corridors across North-East India.
    Stores dynamic risk levels, terrain attributes, and rainfall triggers.
    """
    __tablename__ = "risk_locations"

    id = Column(Integer, primary_key=True, index=True)
    name = Column(String(120), nullable=False, index=True)
    state = Column(String(80), nullable=False, index=True)
    district = Column(String(80), nullable=False)
    latitude = Column(Float, nullable=False)
    longitude = Column(Float, nullable=False)
    elevation_m = Column(Float, nullable=False)
    slope_deg = Column(Float, nullable=False)
    
    # Rainfall and environmental indicators
    rainfall_1d_mm = Column(Float, default=0.0)
    rainfall_3d_mm = Column(Float, default=0.0)
    rainfall_7d_mm = Column(Float, default=0.0)
    soil_moisture_percent = Column(Float, nullable=True)

    # Risk assessment output
    risk_score = Column(Float, default=0.0)  # Range 0.0 - 1.0
    risk_level = Column(String(20), default="LOW")  # LOW, MODERATE, HIGH, CRITICAL
    contributing_factors = Column(Text, nullable=True)  # JSON or comma-separated summary

    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)
    is_demo_data = Column(Boolean, default=True, nullable=False)


class Alert(Base):
    """
    Early warning alert logs generated by threshold triggers or risk assessments.
    """
    __tablename__ = "alerts"

    id = Column(Integer, primary_key=True, index=True)
    location_name = Column(String(120), nullable=False)
    state = Column(String(80), nullable=False)
    latitude = Column(Float, nullable=False)
    longitude = Column(Float, nullable=False)
    risk_level = Column(String(20), nullable=False)  # LOW, MODERATE, HIGH, CRITICAL
    title = Column(String(200), nullable=False)
    message = Column(Text, nullable=False)
    recommended_action = Column(Text, nullable=True)

    acknowledged = Column(Boolean, default=False, nullable=False)
    acknowledged_at = Column(DateTime, nullable=True)
    acknowledged_by = Column(String(100), nullable=True)

    created_at = Column(DateTime, default=datetime.utcnow)
    is_demo_data = Column(Boolean, default=True, nullable=False)


class IncidentReport(Base):
    """
    Citizen and field verification reports of landslides, rockfalls, or road blockages.
    """
    __tablename__ = "incident_reports"

    id = Column(Integer, primary_key=True, index=True)
    reporter_name = Column(String(100), default="Anonymous")
    contact_number = Column(String(30), nullable=True)
    location_name = Column(String(150), nullable=False)
    latitude = Column(Float, nullable=False)
    longitude = Column(Float, nullable=False)
    severity = Column(String(20), nullable=False)  # LOW, MODERATE, HIGH, CRITICAL
    description = Column(Text, nullable=False)
    road_blocked = Column(Boolean, default=False, nullable=False)
    infrastructure_impact = Column(String(150), nullable=True)
    photo_url = Column(String(255), nullable=True)

    status = Column(String(20), default="PENDING")  # PENDING, VERIFIED, RESOLVED
    priority_score = Column(Float, default=0.0)
    priority_level = Column(String(20), default="LOW")  # LOW, MEDIUM, HIGH, CRITICAL

    submitted_at = Column(DateTime, default=datetime.utcnow)
    is_demo_data = Column(Boolean, default=True, nullable=False)


class HistoricalLandslide(Base):
    """
    Validated historical landslide ground-truth records across North-East India
    used for spatial risk overlay and ML validation.
    """
    __tablename__ = "historical_landslides"

    id = Column(Integer, primary_key=True, index=True)
    location_name = Column(String(150), nullable=False)
    state = Column(String(80), nullable=False)
    district = Column(String(80), nullable=False)
    latitude = Column(Float, nullable=False)
    longitude = Column(Float, nullable=False)
    event_date = Column(String(30), nullable=False)
    trigger_type = Column(String(100), default="Monsoon Downpour")
    rainfall_cumulative_mm = Column(Float, nullable=True)
    slope_deg = Column(Float, nullable=True)
    damage_summary = Column(Text, nullable=True)
    fatalities = Column(Integer, default=0)
    road_blocked = Column(Boolean, default=True)
    data_source = Column(String(120), default="GSI / State Disaster Authority Archive")
    is_demo_data = Column(Boolean, default=True, nullable=False)
